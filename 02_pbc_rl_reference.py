#!/usr/bin/env python3
"""PBC+RL reference generation.

Pipeline (fixed for the paper):
  1. Lanczos 2x upsampling
  2. Reflect padding
  3. Richardson-Lucy deconvolution (default 300 iterations)
  4. Unpadding
  5. Center crop to 2x the original size

The PSF is expected to be generated externally, e.g. with the Fiji
PSF Generator plugin (Gibson-Lanni model, NA 1.5, 32.5 nm effective
pixel size, 488 or 561 nm excitation).
"""

import argparse
from pathlib import Path

import cv2
import numpy as np
import tifffile
from scipy.signal import fftconvolve


def load_psf(path: Path) -> np.ndarray:
    psf = tifffile.imread(path).astype(np.float64)
    if psf.ndim == 3:
        psf = psf[psf.shape[0] // 2]
    if psf.ndim != 2:
        raise ValueError(f"Unsupported PSF dimension {psf.ndim}: {path}")
    if psf.sum() <= 0:
        raise ValueError(f"PSF has non-positive sum: {path}")
    return psf / psf.sum()


def crop_psf_to_support(psf: np.ndarray, energy_threshold: float = 0.999) -> np.ndarray:
    psf = psf.astype(np.float64)
    psf = psf / psf.sum()
    h, w = psf.shape
    total = psf.sum()
    target = total * energy_threshold

    yy, xx = np.indices(psf.shape)
    cy = int(round((yy * psf).sum() / total))
    cx = int(round((xx * psf).sum() / total))

    for radius in range(1, max(h, w)):
        y1, y2 = max(0, cy - radius), min(h, cy + radius + 1)
        x1, x2 = max(0, cx - radius), min(w, cx + radius + 1)
        if psf[y1:y2, x1:x2].sum() >= target:
            cropped = psf[y1:y2, x1:x2]
            if cropped.shape[0] % 2 == 0:
                cropped = cropped[:-1, :]
            if cropped.shape[1] % 2 == 0:
                cropped = cropped[:, :-1]
            return cropped / cropped.sum()

    return psf / psf.sum()


def reflect_pad_image(img: np.ndarray, pad_width: int) -> np.ndarray:
    return np.pad(img, pad_width=pad_width, mode="reflect")


def upsample_lanczos(img: np.ndarray, scale: float) -> np.ndarray:
    h, w = img.shape[:2]
    new_size = (int(round(w * scale)), int(round(h * scale)))
    return cv2.resize(img, new_size, interpolation=cv2.INTER_LANCZOS4)


def rl_deconvolution(
    image: np.ndarray,
    psf: np.ndarray,
    iterations: int = 300,
    eps: float = 1e-8,
) -> np.ndarray:
    img = np.maximum(image.astype(np.float64), 0)
    psf = psf.astype(np.float64)
    psf = psf / psf.sum()

    img_max = img.max()
    if img_max > 0:
        img = img / img_max

    deconv = img.copy()
    psf_flip = np.flip(psf)

    for _ in range(iterations):
        conv = fftconvolve(deconv, psf, mode="same")
        np.maximum(conv, eps, out=conv)
        relative_blur = img / conv
        error_est = fftconvolve(relative_blur, psf_flip, mode="same")
        np.maximum(error_est, eps, out=error_est)
        deconv *= error_est
        np.maximum(deconv, 0, out=deconv)
        np.clip(deconv, 0, 3.0, out=deconv)

    return (deconv * img_max).astype(np.float32)


def center_crop(img: np.ndarray, size: tuple[int, int]) -> np.ndarray:
    h, w = size
    H, W = img.shape
    start_h = max(0, (H - h) // 2)
    start_w = max(0, (W - w) // 2)
    return img[start_h:start_h + h, start_w:start_w + w]


def process_image(
    img: np.ndarray,
    psf: np.ndarray,
    pad_width: int,
    iterations: int,
    scale: float,
) -> np.ndarray:
    orig_h, orig_w = img.shape

    current = upsample_lanczos(img, scale)
    current = reflect_pad_image(current, pad_width)
    current = rl_deconvolution(current, psf, iterations=iterations)
    current = current[pad_width:-pad_width, pad_width:-pad_width]

    target_h = int(round(orig_h * scale))
    target_w = int(round(orig_w * scale))
    if current.shape != (target_h, target_w):
        current = center_crop(current, (target_h, target_w))
    return current


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="PBC+RL reference generation (Lanczos 2x + RL)."
    )
    p.add_argument("--in-dir", required=True, type=Path,
                   help="Directory with PBC images.")
    p.add_argument("--out-dir", required=True, type=Path,
                   help="Directory to write PBC+RL images.")
    p.add_argument("--psf", required=True, type=Path,
                   help="PSF TIFF generated by Fiji PSF Generator.")
    p.add_argument("--iterations", type=int, default=300,
                   help="RL iterations. Paper setting: 300.")
    p.add_argument("--pad-width", type=int, default=64)
    p.add_argument("--scale", type=float, default=2.0)
    p.add_argument("--pattern", default="*.tif*")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    if not args.in_dir.exists():
        raise FileNotFoundError(f"Input directory not found: {args.in_dir}")
    args.out_dir.mkdir(parents=True, exist_ok=True)

    psf = load_psf(args.psf)
    psf = crop_psf_to_support(psf, energy_threshold=0.999)
    print(f"PSF loaded: shape={psf.shape}, sum={psf.sum():.6f}")

    files = sorted(args.in_dir.glob(args.pattern))
    if not files:
        raise FileNotFoundError(
            f"No files matching {args.pattern} in {args.in_dir}"
        )

    print(f"Found {len(files)} input image(s)")
    for f in files:
        try:
            img = tifffile.imread(f).astype(np.float32)
            if img.ndim != 2:
                raise ValueError(f"Expected 2D image, got shape={img.shape}")
            out = process_image(
                img, psf, args.pad_width, args.iterations, args.scale
            )
            tifffile.imwrite(args.out_dir / f.name, out)
            print(f"  {f.name}: {img.shape} -> {out.shape}")
        except Exception as exc:
            print(f"  {f.name}: ERROR: {exc}")


if __name__ == "__main__":
    main()